#!/usr/bin/env python3
"""Import the pinned selected export without changing retained profiles."""
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "parameters/reference/selected-original.json"
EXPECTED = "470df5f9ba3d18a8b0e3f003e1d4bda4e7557a6021ad3767d68e12a0894def58"
MOD1_SOURCE = ROOT / "parameters/identity19_mod1_reference.json"
MOD1_EXPECTED = "0486ff0d24515dda43f44c61664fe002112e5949ca7a17f365f6900061ddb387"


def main():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        raise SystemExit("Pinned selected export hash mismatch")
    records = json.loads(raw)
    mod1_raw = MOD1_SOURCE.read_bytes()
    if hashlib.sha256(mod1_raw).hexdigest() != MOD1_EXPECTED:
        raise SystemExit("Pinned K20 Mod1 export hash mismatch")
    lines = [
        '// Generated by unittest/tools/import_boot_parameters.py.',
        '// Pinned export SHA256: ' + EXPECTED,
        '// Joint K20/DA2/L29 -> L21 retuned on 2026-10-15; Q/P are unchanged.',
        '#include "extension/BootParameter.h"',
        '#include <cmath>',
        '#include "common/CommonUtils.h"',
        '#include "common/Assert.h"',
        '',
        'namespace cheddar {',
        'BootParameter BootParameter::Identity19() {',
        '  return Selected(BootRoute::kIdentity19);',
        '}',
        '',
        'BootParameter BootParameter::DiscreteCKKSMeBoot() {',
        '  return Selected(BootRoute::kDiscreteCKKSMeBoot);',
        '}',
        '',
        'BootParameter BootParameter::Selected(BootRoute route) {',
        '  BootParameter out{};',
        '  out.route = route;',
    ]
    for name, enum, output in [("joint4434", "kIdentity19", "identity19_meboot"),
                               ("ordinary", "kOrdinary", "ordinary")]:
        r = json.loads(json.dumps(records[name]))
        if name == "joint4434":
            r.update(json.loads(mod1_raw))
            r["mod1"]["LevelQ"] = records[name]["mod1"]["LevelQ"]
            r["mod1_reference_sha256"] = MOD1_EXPECTED
            # Keep the entry integer period while reducing the lift multiplier.
            r["stc_intermediate_scale_log2_override"] = 37.875
            r["stc_output_scale_log2_override"] = 33
            output_scale = math.exp2(r["stc_output_scale_log2_override"])
            scale_down = max(1, math.floor(r["q"][0] / 1024 / output_scale + 0.5))
            modup = math.floor(math.exp2(48) / (output_scale * scale_down) + 0.5)
            return_gain = modup / 65536
            r["mod1"]["Scaling"] *= return_gain
            amplitude = math.pow(return_gain, 1 / (1 << r["mod1"]["DoubleAngle"]))
            for coefficient in r["mod1_coefficients_float64"]:
                coefficient[0] *= amplitude
            r["mod1_sqrt2pi"] *= amplitude
            r["native_scaling_binding"] = {
                "reference_stc_intermediate_log_scale": 37.49017137195595,
                "reference_stc_output_log_scale": 32,
                "reference_mod1_scaling": 0.25,
                "scale_down_integer_multiplier": scale_down,
                "modup_integer_multiplier": modup,
                "proper_cts_gain_multiplier": 1 / return_gain,
                "mod1_return_gain_multiplier": return_gain,
                "mod1_initial_amplitude_multiplier": amplitude,
                "q_p_unchanged": True,
            }
        lines.append(f'  if (route == BootRoute::{enum}) {{')
        for member, values in [
            ("q", r["q"]), ("p", r["p"]),
            ("coefficients", [c[0] for c in r["mod1_coefficients_float64"]]),
            ("widths", r["cts"]["CustomedMerge"]),
            ("bases", r["joint_design"]["Bases"] if name == "joint4434"
             else r["ordinary_bases"]),
        ]:
            assert member != "coefficients" or all(c[1] == 0 for c in r["mod1_coefficients_float64"])
            lines.append(f'    out.{member} = {{' + ", ".join(map(str, values)) + '};')
        fields = {
            "extra_q": r.get("proper_extra_q", 0),
            "sparse_h": r["subring_h"] or r["ephemeral_h"],
            "extension": r["subring_extension"] or 1,
            "basis_lift": r["mod1_power_basis_scale_lift"],
            "mod1_level": r["mod1"]["LevelQ"],
            "k": r["mod1"]["K"], "q_diff": r["mod1_q_diff"],
            "sqrt2pi": r["mod1_sqrt2pi"],
            "double_angle": r["mod1"]["DoubleAngle"],
            "interval_a": r["mod1_interval_a"], "interval_b": r["mod1_interval_b"],
        }
        for member, value in fields.items():
            lines.append(f'    out.{member} = {value};')
        for member, field in [
            ("stc_intermediate_log_scale", "stc_intermediate_scale_log2_override"),
            ("stc_output_log_scale", "stc_output_scale_log2_override"),
        ]:
            value = r[field]
            lines.append(f'    out.{member} = ' + (str(value) if value else "std::nullopt") + ';')
        lines.extend(['    return out;', '  }'])
        profile = dict(r)
        profile.update({
            "reference_revision": "6330f64b178b6215edd35baf5b11c8da558ca95c",
            "reference_export_sha256": EXPECTED,
            "implementation_status": (
                "precision-verified-single-keyset; "
                "independent-keysets-and-paired-baseline-pending; "
                "security-unqualified"),
            "log_degree": 16, "dense_hamming_weight": 2048,
            "input_level": 2, "input_log_scale": 40,
            "output_level": r["mod1"]["LevelQ"] - math.ceil(
                math.log2(len(r["mod1_coefficients_float64"]))) - r["mod1"]["DoubleAngle"],
            "output_log_scale": 40,
            "entry_error_sigma": 3.2,
        })
        if name == "joint4434":
            profile["implementation_status"] = (
                "precision-verified-single-keyset; latency-measured-single-keyset; "
                "independent-keysets-and-paired-baseline-pending; "
                "classical-heuristic-security-screen-verified")
            profile["security_screen_evidence"] = (
                "docs/evidence/identity19/security.json")
        (ROOT / f"parameters/{output}.json").write_text(
            json.dumps(profile, indent=2) + "\n", encoding="ascii")
    lines.extend([
        '  throw std::invalid_argument("Unknown selected boot route");',
        '}',
        '',
        'void BootParameter::ValidateScalingBinding() const {',
        '  const double stc_output = std::exp2(stc_output_log_scale.value_or(40));',
        '  const double entry_scale = stc_output * ScaleDownMultiplier();',
        '  const double lifted_scale = entry_scale * ModUpMultiplier();',
        '  AssertTrue(std::abs(lifted_scale / kModUpScale - 1.0) < 1e-12,',
        '             "Selected lift scale binding mismatch");',
        '  AssertTrue(std::abs(ProperCtSGain() * Mod1ReturnGain() / CtSGain() - 1.0) <',
        '                 1e-12,',
        '             "Selected CtS/Mod1 return gain binding mismatch");',
        '  AssertTrue(std::abs(CorrectionGain() /',
        '                          (k * q_diff * kOutputGain * Mod1ReturnGain()) -',
        '                      1.0) <',
        '                 1e-12,',
        '             "Selected correction gain binding mismatch");',
        '  if (route == BootRoute::kIdentity19 ||',
        '      route == BootRoute::kDiscreteCKKSMeBoot) {',
        '    AssertTrue(stc_intermediate_log_scale.has_value() &&',
        '                   *stc_intermediate_log_scale > 0 &&',
        '                   stc_output_log_scale.has_value() &&',
        '                   *stc_output_log_scale > 0,',
        '               "Joint selected StC scale binding is incomplete");',
        '    AssertTrue(std::abs(ScaleDownMultiplier() - 1.0) < 1e-12,',
        '               "Joint selected ScaleDown binding changed");',
        '  }',
        '}',
        '',
        'std::unique_ptr<Parameter<uint64_t>> BootParameter::MakeParameter() const {',
        '  std::vector<std::pair<int, int>> levels;',
        '  for (int i = 1; i <= 32; ++i) levels.emplace_back(i, 0);',
        '  std::vector<uint64_t> terminal, entry;',
        '  if (extra_q) {',
        '    terminal.push_back(extra_q);',
        '    entry.push_back(786433);',
        '    levels.emplace_back(32, 1);',
        '  }',
        '  auto result = std::make_unique<Parameter<uint64_t>>(',
        '      16, kApplicationScale, OutputLevel(), levels, q, p, terminal,',
        '      std::pair<int, int>{0, 0}, 31, entry);',
        '  result->SetSparseHammingWeight(sparse_h);',
        '  result->SetDenseHammingWeight(2048);',
        '  return result;',
        '}',
        '',
        'double BootParameter::ScaleDownMultiplier() const {',
        '  const double rounded = std::round(double(q[0]) / 1024 /',
        '      std::exp2(stc_output_log_scale.value_or(40)));',
        '  return IsMEBootRoute(route) ? std::max(1.0, rounded) : rounded;',
        '}',
        '',
        'double BootParameter::ModUpMultiplier() const {',
        '  const double entry_scale = std::exp2(stc_output_log_scale.value_or(40)) *',
        '      ScaleDownMultiplier();',
        '  return std::round(kModUpScale / entry_scale);',
        '}',
        '',
        'double BootParameter::Mod1ReturnGain() const {',
        '  return IsMEBootRoute(route) ? ModUpMultiplier() / 65536 : 1;',
        '}',
        '',
        'int BootParameter::OutputLevel() const {',
        '  return mod1_level - Log2Ceil(coefficients.size()) - double_angle;',
        '}',
        '',
        'double BootParameter::Mod1PolynomialTargetScale() const {',
        '  // Invert DA rescaling from the last consumed prime to the first.',
        '  double target = kMod1Scale;',
        '  for (int i = 0; i < double_angle; ++i) {',
        '    target = std::sqrt(target * static_cast<double>(q.at(OutputLevel() + 1 + i)));',
        '  }',
        '  return target;',
        '}',
        '}  // namespace cheddar',
    ])
    lines.insert(4, '#include <stdexcept>')
    lines.insert(4, '#include <algorithm>')
    (ROOT / "src/extension/BootParameter.cpp").write_text(
        "\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
